# Задание 1. Основы Python
# Тема: Магазин

# Запрашиваем имя покупателя
# Тип данных str
name = input("Введите ваше имя: ")

# Создаём список доступных товаров
products = ["хлеб", "молоко", "сыр", "яблоки"]

# Выводим список товаров на экран
print("\nДоступные товары:")

# Используем цикл for для вывода каждого товара
for product in products:
    print("-", product)

# Пользователь выбирает товар
choice = input("\nВведите название товара: ").lower()

# Проверяем, есть ли выбранный товар в списке
if choice in products:

    # Запрашиваем цену товара
    # Сначала получаем строку, затем заменяем запятую на точку
    price = input("Введите цену одного товара: ")
    price = float(price.replace(",", "."))

    # Запрашиваем количество товара
    # Тип данных int
    quantity = int(input("Введите количество товара: "))

    # Арифметическая операция
    # Вычисляем общую стоимость
    total = price * quantity

    # Собственная функция для расчёта скидки
    def calculate_discount(amount):
        # Если сумма покупки 1000 рублей или больше,
        # предоставляем скидку 10%
        if amount >= 1000:
            return amount * 0.10
        else:
            return 0

    # Вызываем нашу функцию
    discount = calculate_discount(total)

    # Вычисляем итоговую стоимость
    final_price = total - discount

    # Объединяем строки с помощью оператора +
    greeting = "Здравствуйте, " + name + "!"

    # Выводим информацию о покупке
    print("\n" + greeting)
    print("Выбранный товар: " + choice)
    print("Цена одного товара:", price, "руб.")
    print("Количество:", quantity)
    print("Стоимость покупки:", total, "руб.")
    print("Скидка:", discount, "руб.")
    print("Итоговая стоимость:", final_price, "руб.")

else:
    # Если товара нет в списке
    print("\n" + name + ", такого товара нет в списке.")

# Завершающее сообщение, изменение для коммита
print("Спасибо за покупку. Задание 1 - выполнено - клонирование репозитория")
